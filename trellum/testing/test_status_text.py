"""Semantic small-text roles preserve constructor and author-color contracts."""
import hashlib
import importlib.util
import inspect
import json
from dataclasses import dataclass, fields
from pathlib import Path

import pytest

from trellum.components import ComparisonTable
from trellum.components.base import RenderContext
from trellum.report import ReportContext
from trellum.reporting.diagnostics import compute_details
from trellum.themes import DEFAULT_THEME, DEFAULT_THEME_NAME, THEME_REGISTRY, Theme
from trellum.validation import validate_report

ROLES = ('text_positive', 'text_negative', 'text_warning', 'text_context')
LEGACY = ('accent_green', 'accent_red', 'accent_yellow', 'text_muted')


def examples():
    path = Path(__file__).parents[1] / 'demo/reports/component-showcase/examples_status_text.py'
    spec = importlib.util.spec_from_file_location('examples_status_text', path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def report(output):
    ctx = ReportContext({
        'name': 'Status text examples', 'studio': 'framework', 'category': 'Components',
        'theme': 'trellum light',
        'description': 'Synthetic weekly report metrics demonstrate supplied favorable, unfavorable, '
                       'forecast and context text, with declared metric directions and unavailable reasons.',
    }, 'status-text', str(output))
    examples().add_sections(ctx)
    return ctx


def test_roles_are_keyword_only_and_preserve_subclass_positions():
    @dataclass
    class CaptionTheme(Theme):
        caption: str = 'caption'

    old = [f for f in fields(Theme) if f.name not in ROLES]
    values = [getattr(Theme(), f.name) for f in old]
    theme = CaptionTheme(*values, 'positional caption', text_positive='#123456')
    assert theme.caption == 'positional caption'
    assert theme.text_positive == '#123456'
    for role in ROLES:
        assert inspect.signature(Theme).parameters[role].kind is inspect.Parameter.KEYWORD_ONLY
    with pytest.raises(TypeError):
        Theme(*values, '#123456')


def test_builtin_old_tokens_and_palettes_are_identical_to_dependency_baseline():
    old = {name: {k: v for k, v in theme.to_dict().items() if k not in ROLES}
           for name, theme in THEME_REGISTRY.items()}
    # All old fields of the thirteen named themes at dependency 24cd1cf.
    assert hashlib.sha256(json.dumps(old, sort_keys=True).encode()).hexdigest() == 'f2bb16da60f4a4424c6ada2623de23fc684cee682cab69babf013e922a5c577d'
    assert len(THEME_REGISTRY) == 13
    assert DEFAULT_THEME_NAME == 'trellum dark'
    assert DEFAULT_THEME is THEME_REGISTRY[DEFAULT_THEME_NAME]


@pytest.mark.parametrize('name', THEME_REGISTRY)
def test_builtin_roles_are_authored_and_serialized(name):
    theme = THEME_REGISTRY[name]
    for role in ROLES:
        value = getattr(theme, role)
        assert value.startswith('#') and len(value) == 7
        assert theme.to_dict()[role] == value
        assert f'--{role.replace("_", "-")}: {value};' in theme.to_css_vars()


def test_custom_theme_aliases_and_explicit_roles_serialize_unchanged():
    custom = Theme(bg_card='#101020', accent_green='#99ff99', text_muted='#aaaabb')
    for role, legacy in zip(ROLES, LEGACY):
        value = f'var(--{legacy.replace("_", "-")})'
        assert getattr(custom, role) == custom.to_dict()[role] == value
        assert f'--{role.replace("_", "-")}: {value};' in custom.to_css_vars()
    supplied = dict(zip(ROLES, ['#135724', 'var(--authored-danger)', '#fef0af', '#abcdef']))
    override = Theme(**supplied)
    for role, value in supplied.items():
        assert override.to_dict()[role] == value
        assert f'--{role.replace("_", "-")}: {value};' in override.to_css_vars()


def test_autogenerated_rules_use_roles_and_authored_rules_remain_exact():
    frame, context = examples().status_fixture()
    rules = {'Change': [{'op': '>', 'value': 0, 'color': 'var(--accent-green)'},
                        {'op': '<', 'value': 0, 'color': '#b1457b'}]}
    before = json.dumps(rules)
    for declared in (None, context):
        for supplied in (None, {}, rules):
            ctx = RenderContext(DEFAULT_THEME)
            ComparisonTable(frame, 'Colors', 'Current', ['Change'], static=True,
                            comparison_context=declared, conditional_formats=supplied).render_html(ctx)
            cfg = next(iter(ctx.component_data.values()))
            assert cfg['comparison']['autoColors'] is (supplied is None)
            if supplied:
                assert cfg['conditionalFormats'] == rules
            elif supplied == {} or declared is not None:
                assert 'conditionalFormats' not in cfg
            else:
                assert [r['color'] for r in cfg['conditionalFormats']['Change']] == [
                    'var(--text-positive, var(--accent-green))',
                    'var(--text-negative, var(--accent-red))',
                ]
    assert json.dumps(rules) == before


def test_genuine_module_report_passes_full_diagnostics_and_build(tmp_path):
    from trellum.rendering.html_builder import render_report

    ctx = report(tmp_path)
    details = compute_details(ctx)
    result = validate_report(ctx, details=details)
    assert result.summary['fail'] == result.summary['warn'] == 0, result.to_dict()
    render_report(ctx, auto_refresh=False, validation=result, details=details)
    assert (tmp_path / 'index.html').is_file()
