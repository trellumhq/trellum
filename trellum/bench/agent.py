"""Build a cold project, drop a headless agent into it, record what happened.

The scratch project is scaffolded by the real ``python -m trellum.init``, so
whatever a new user gets is exactly what the agent gets -- pointer files,
hooks, an empty data-sources/config.yaml, and no .env. If scaffolding improves,
the benchmark measures the improvement without anyone updating this file.

How the framework becomes importable is deliberate. A pip-installed framework
sits in site-packages: outside the project, reachable but not underfoot. To
reproduce that we generate a one-file shim package in ``results/pylib/`` and
put *that* directory on PYTHONPATH -- not the repo root, which would expose the
whole monorepo, and not a shim inside the project, which would put framework
source in the agent's own tree and quietly change the thing we are measuring.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import time
from pathlib import Path

_BENCH_DIR = Path(__file__).resolve().parent
_FRAMEWORK_DIR = _BENCH_DIR.parent
_RESULTS_DIR = _BENCH_DIR / "results"
_PYLIB_DIR = _RESULTS_DIR / "pylib"

# Mirrors itest/project/trellum/__init__.py, with the framework root baked in
# absolutely instead of walked to with os.pardir hops -- this copy is generated
# outside the repo tree, so there is no fixed number of hops to walk.
_SHIM = '''\
"""Generated by trellum/bench -- do not edit. Makes the framework importable
from a scratch project the way a pip install would, without putting framework
source inside the project under test."""

import os

_REPO_ROOT = r"{framework}"

__path__ = [_REPO_ROOT]

_real_init = os.path.join(_REPO_ROOT, "__init__.py")
with open(_real_init, encoding="utf-8") as _fh:
    exec(compile(_fh.read(), _real_init, "exec"))
'''


def ensure_pylib() -> Path:
    """Create/refresh the shim package. Returns the dir to put on PYTHONPATH."""
    pkg = _PYLIB_DIR / "trellum"
    pkg.mkdir(parents=True, exist_ok=True)
    (pkg / "__init__.py").write_text(
        _SHIM.format(framework=str(_FRAMEWORK_DIR)), encoding="utf-8"
    )
    return _PYLIB_DIR


def child_env() -> dict:
    """Environment for every subprocess: the agent, and the grader's build."""
    env = dict(os.environ)
    env["PYTHONPATH"] = str(ensure_pylib())
    # Keep the harness's own credentials out of the scratch project. The agent
    # must write its own .env from the prose in the task -- inheriting ours
    # would hand it the answer and score a journey nobody took.
    for key in list(env):
        if key.startswith(("BI_", "TRELLUM_DS_")):
            del env[key]
    return env


def make_scratch(run_id: str, py: str,
                 preexisting: tuple[tuple[str, str], ...] = ()) -> Path:
    """Scaffold a fresh project with the real init command.

    ``preexisting`` files are written first, so the scaffolder meets a project
    that already has its own conventions rather than an empty directory.
    """
    scratch = _RESULTS_DIR / "scratch" / run_id
    if scratch.exists():
        shutil.rmtree(scratch)
    scratch.mkdir(parents=True)
    for name, content in preexisting:
        target = scratch / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")

    result = subprocess.run(
        [py, "-m", "trellum.init", str(scratch)],
        cwd=str(_FRAMEWORK_DIR.parent),
        env=child_env(),
        capture_output=True, text=True, timeout=120,
    )
    if result.returncode != 0:
        raise RuntimeError(
            f"trellum.init failed ({result.returncode}) -- the harness cannot "
            f"build a scratch project.\n{result.stdout}\n{result.stderr}"
        )
    return scratch


def install_skill(scratch: Path, py: str) -> None:
    """The `--guidance skills` arm: drop the prototype thin skill in place.

    ``{py}`` is substituted for the same reason agentsetup does it: a bare
    ``trellum`` is only on PATH inside an activated virtualenv, and agents do
    not activate virtualenvs.
    """
    src = _BENCH_DIR / "assets" / "SKILL.md"
    dest = scratch / ".claude" / "skills" / "trellum" / "SKILL.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    text = src.read_text(encoding="utf-8").replace("{py}", Path(py).as_posix())
    dest.write_text(text, encoding="utf-8")


def _claude_bin() -> str:
    found = shutil.which("claude")
    if not found:
        raise RuntimeError(
            "`claude` is not on PATH -- the bench drives the Claude Code CLI. "
            "Install it, or run with --dry-run to check the harness itself."
        )
    return found


def claude_version() -> str:
    try:
        out = subprocess.run(
            [_claude_bin(), "--version"],
            capture_output=True, text=True, timeout=30,
        )
        return (out.stdout or "").strip()
    except Exception:
        return "unknown"


def _find_transcript(session_id: str | None, since: float) -> Path | None:
    """Locate the session JSONL Claude Code wrote for this run.

    Keyed on session_id when we have one. On a timeout there is no result JSON
    and therefore no id, so fall back to the newest transcript touched after
    the run started -- worth having, since a timed-out run is exactly the one
    whose transcript someone will want to read.
    """
    base = Path.home() / ".claude" / "projects"
    if not base.is_dir():
        return None
    if session_id:
        for path in base.glob(f"*/{session_id}.jsonl"):
            return path
    candidates = [
        p for p in base.glob("*/*.jsonl") if p.stat().st_mtime >= since
    ]
    if not candidates:
        return None
    return max(candidates, key=lambda p: p.stat().st_mtime)


def run_agent(prompt: str, scratch: Path, run_id: str, *,
              model: str, max_turns: int, timeout_s: int) -> dict:
    """Run one headless agent turn-loop. Never raises on agent failure."""
    # The prompt goes in on stdin, not as an argv element. On Windows `claude`
    # is a .CMD, so every argument is routed through cmd.exe -- which truncates
    # arguments at an embedded newline. A multi-line task passed as argv dies
    # silently: exit 0, no output, no session. stdin has no such problem, and
    # behaves identically on POSIX.
    cmd = [
        _claude_bin(), "-p",
        "--output-format", "json",
        "--max-turns", str(max_turns),
        # An allowlist is the instinct here, but headless mode auto-denies
        # anything unlisted -- an under-scoped list produces permission
        # refusals that look like DX failures and poison the measurement. The
        # scratch project is disposable and the agent already has Bash.
        # ponytail: no filesystem jail; add deny rules before this runs
        # unattended on a shared machine.
        "--dangerously-skip-permissions",
        "--model", model,
    ]

    started = time.time()
    proc = subprocess.Popen(
        cmd, cwd=str(scratch), env=child_env(),
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
        encoding="utf-8", errors="replace",
    )
    timed_out = False
    try:
        stdout, stderr = proc.communicate(input=prompt, timeout=timeout_s)
    except subprocess.TimeoutExpired:
        timed_out = True
        proc.kill()
        stdout, stderr = proc.communicate()
    wall_s = round(time.time() - started, 1)

    payload: dict = {}
    if stdout:
        try:
            payload = json.loads(stdout)
        except json.JSONDecodeError:
            # Defensive: --output-format json emits one object, but a crash
            # mid-stream leaves fragments. Keep the tail for the record.
            payload = {"result": stdout[-2000:]}

    # `subtype` is how the CLI reports *why* it stopped. A max-turns abort
    # still exits 0 with a well-formed result, so without this a run that was
    # cut off mid-investigation is indistinguishable from one that finished
    # and had nothing to say -- and the first is not a measurement.
    subtype = payload.get("subtype") or ""
    turns = payload.get("num_turns")
    hit_turn_cap = "max_turns" in subtype or (
        isinstance(turns, int) and turns >= max_turns
    )

    session_id = payload.get("session_id")
    transcript = _find_transcript(session_id, started)
    saved = None
    if transcript and transcript.is_file():
        saved = _RESULTS_DIR / "transcripts" / f"{run_id}.jsonl"
        saved.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(transcript, saved)

    return {
        "wall_s": wall_s,
        "timed_out": timed_out,
        "result_text": payload.get("result") or "",
        "session_id": session_id,
        "num_turns": turns,
        "total_cost_usd": payload.get("total_cost_usd"),
        "is_error": bool(payload.get("is_error")) or timed_out,
        "stop_subtype": subtype,
        "hit_turn_cap": hit_turn_cap,
        "model": payload.get("model") or model,
        # Kept regardless of exit code: the CLI can exit 0 having produced
        # nothing useful, and that is exactly the case worth diagnosing.
        "stderr_tail": (stderr or "").strip()[-2000:],
        "no_result_json": not payload.get("type") and not payload.get("result"),
        "transcript": str(saved.relative_to(_BENCH_DIR)) if saved else None,
    }
